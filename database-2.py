def _touch_streak(cur, uid):
    """Обновляет streak пользователя. Вызывается ВНУТРИ уже открытой транзакции
    (использует переданный cursor), с блокировкой строки (FOR UPDATE), чтобы
    один и тот же день не засчитывался дважды при параллельных запросах."""
    cur.execute("SELECT last_activity_date, streak FROM users WHERE id=%s FOR UPDATE", (uid,))
    row = cur.fetchone()
    if not row:
        return
    last_date, streak = row
    today = date.today()
    if last_date == today:
        return  # сегодняшний день уже засчитан
    if last_date == today - timedelta(days=1):
        new_streak = (streak or 0) + 1
    else:
        new_streak = 1
    cur.execute("UPDATE users SET streak=%s, last_activity_date=%s WHERE id=%s", (new_streak, today, uid))


