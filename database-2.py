# ─────────────────────────────────────────────────────────────────────────
# Схема БД и миграции. Ничего не удаляет и не пересоздаёт с нуля — только
# CREATE TABLE IF NOT EXISTS / ADD COLUMN IF NOT EXISTS, поэтому безопасно
# запускать повторно на уже существующей базе с реальными пользователями.
# ─────────────────────────────────────────────────────────────────────────

def _ensure_autoincrement(cur, table, column="id"):
    """Делает столбец column таблицы table автоинкрементным (через отдельную
    SEQUENCE), если он им ещё не является. Нужно для таблицы words: раньше id
    проставлялся вручную (1001, 2001, ...), теперь новые слова из WORD_GROUPS
    должны получать id автоматически, а старые id не должны меняться."""
    seq_name = f"{table}_{column}_seq"
    cur.execute("SELECT 1 FROM pg_class WHERE relkind='S' AND relname=%s", (seq_name,))
    if cur.fetchone():
        return
    cur.execute(f"CREATE SEQUENCE {seq_name}")
    cur.execute(f"SELECT setval('{seq_name}', COALESCE((SELECT MAX({column}) FROM {table}), 0))")
    cur.execute(f"ALTER TABLE {table} ALTER COLUMN {column} SET DEFAULT nextval('{seq_name}')")
    cur.execute(f"ALTER SEQUENCE {seq_name} OWNED BY {table}.{column}")


def _ensure_constraint(cur, table, constraint_name, ddl):
    """Добавляет ограничение (constraint), только если его ещё нет — Postgres
    не поддерживает 'ADD CONSTRAINT IF NOT EXISTS' напрямую."""
    cur.execute("SELECT 1 FROM pg_constraint WHERE conname=%s", (constraint_name,))
    if cur.fetchone():
        return
    cur.execute(f"ALTER TABLE {table} ADD CONSTRAINT {constraint_name} {ddl}")


def setup_database():
    """Создаёт/дополняет таблицы (если их нет) и синхронизирует каталог слов.
    Безопасно для повторного запуска и для уже существующей базы с данными."""
    conn = db_connect()
    try:
        cur = conn.cursor()

        # ---- users: базовая таблица (как раньше) + новые поля профиля ----
        cur.execute('''
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT PRIMARY KEY,
                name TEXT DEFAULT '',
                level TEXT DEFAULT '',
                last_word_id INTEGER DEFAULT 0,
                test_words TEXT DEFAULT '',
                daily_words TEXT DEFAULT '',
                manual_words TEXT DEFAULT ''
            )
        ''')
        # Старые поля (level, last_word_id, test_words, daily_words, manual_words)
        # намеренно не трогаем и не удаляем — это часть старой механики уровней,
        # они больше не используются новым кодом, но их наличие не мешает и не
        # рискует данными существующих пользователей.
        cur.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS daily_time TEXT DEFAULT NULL")
        cur.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS registered BOOLEAN NOT NULL DEFAULT FALSE")
        cur.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS balance INTEGER NOT NULL DEFAULT 0")
        cur.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS streak INTEGER NOT NULL DEFAULT 0")
        cur.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS last_activity_date DATE")
        cur.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS last_daily_sent_date DATE")
        cur.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS test_queue TEXT NOT NULL DEFAULT ''")
        cur.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NOT NULL DEFAULT now()")
        _ensure_constraint(cur, "users", "chk_users_balance_nonneg", "CHECK (balance >= 0)")

        # ---- groups: справочник тем ----
        cur.execute('''
            CREATE TABLE IF NOT EXISTS groups (
                key TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                description TEXT NOT NULL DEFAULT '',
                sort_order INTEGER NOT NULL DEFAULT 0,
                active BOOLEAN NOT NULL DEFAULT TRUE
            )
        ''')

        # ---- words: было id/word_bel/word_ru/word_en/level -> теперь group_key ----
        cur.execute('''
            CREATE TABLE IF NOT EXISTS words (
                id INTEGER PRIMARY KEY,
                word_bel TEXT,
                word_ru TEXT
            )
        ''')
        cur.execute("ALTER TABLE words ADD COLUMN IF NOT EXISTS group_key TEXT")
        cur.execute("ALTER TABLE words ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE")
        cur.execute("ALTER TABLE words ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NOT NULL DEFAULT now()")
        # Английский больше не нужен (только бел -> рус); старое поле level
        # (уровни "с нуля/средний/сложный") заменено темами (group_key).
        cur.execute("ALTER TABLE words DROP COLUMN IF EXISTS word_en")
        cur.execute("ALTER TABLE words DROP COLUMN IF EXISTS level")
        # Старые слова (из прошлой версии словаря) не относятся ни к одной новой
        # теме — помечаем неактивными, не удаляя физически.
        cur.execute("UPDATE words SET active=FALSE WHERE group_key IS NULL")
        _ensure_autoincrement(cur, "words", "id")
        _ensure_constraint(
            cur, "words", "uq_words_group_bel_ru",
            "UNIQUE (group_key, word_bel, word_ru)",
        )
        cur.execute("CREATE INDEX IF NOT EXISTS idx_words_group_active ON words (group_key, active)")

        # ---- user_words: какие слова пользователь уже изучил ----
        cur.execute('''
            CREATE TABLE IF NOT EXISTS user_words (
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                word_id INTEGER NOT NULL REFERENCES words(id) ON DELETE CASCADE,
                first_learned_at TIMESTAMP NOT NULL DEFAULT now(),
                last_seen_at TIMESTAMP NOT NULL DEFAULT now(),
                learned BOOLEAN NOT NULL DEFAULT TRUE,
                correct_answers INTEGER NOT NULL DEFAULT 0,
                wrong_answers INTEGER NOT NULL DEFAULT 0,
                review_count INTEGER NOT NULL DEFAULT 0,
                PRIMARY KEY (user_id, word_id)
            )
        ''')
        cur.execute("CREATE INDEX IF NOT EXISTS idx_user_words_user ON user_words (user_id)")

        # ---- currency_tx: история начислений "Бульбы" (для рейтингов) ----
        cur.execute('''
            CREATE TABLE IF NOT EXISTS currency_tx (
                id SERIAL PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                amount INTEGER NOT NULL,
                reason TEXT NOT NULL,
                created_at TIMESTAMP NOT NULL DEFAULT now()
            )
        ''')
        cur.execute("CREATE INDEX IF NOT EXISTS idx_currency_tx_user_created ON currency_tx (user_id, created_at)")

        # ---- games: игровые комнаты 1×1 ----
        cur.execute('''
            CREATE TABLE IF NOT EXISTS games (
                id SERIAL PRIMARY KEY,
                token TEXT NOT NULL UNIQUE,
                group_key TEXT NOT NULL REFERENCES groups(key),
                creator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                player1_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                player2_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
                status TEXT NOT NULL DEFAULT 'waiting',
                round_number INTEGER NOT NULL DEFAULT 0,
                current_word_id INTEGER REFERENCES words(id),
                current_options TEXT NOT NULL DEFAULT '',
                winner_id BIGINT,
                created_at TIMESTAMP NOT NULL DEFAULT now(),
                finished_at TIMESTAMP
            )
        ''')
        cur.execute("CREATE INDEX IF NOT EXISTS idx_games_token ON games (token)")

        # ---- game_answers: ответы игроков по раундам (защита от дублей) ----
        cur.execute('''
            CREATE TABLE IF NOT EXISTS game_answers (
                id SERIAL PRIMARY KEY,
                game_id INTEGER NOT NULL REFERENCES games(id) ON DELETE CASCADE,
                round_number INTEGER NOT NULL,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                word_id_chosen INTEGER,
                correct BOOLEAN NOT NULL,
                created_at TIMESTAMP NOT NULL DEFAULT now(),
                UNIQUE (game_id, round_number, user_id)
            )
        ''')

        conn.commit()

        # ---- синхронизация каталога слов из WORD_GROUPS ----
        sync_word_catalog(cur)
        conn.commit()

        cur.close()
    finally:
        db_release(conn)


def sync_word_catalog(cur):
    """Синхронизирует таблицы groups/words с каталогом WORD_GROUPS выше.
    Можно вызывать многократно (например, при каждом старте бота) — не
    создаёт дублей и не меняет id уже существующих слов."""
    keys = list(WORD_GROUPS.keys())

    for order, key in enumerate(keys):
        data = WORD_GROUPS[key]
        cur.execute('''
            INSERT INTO groups (key, name, description, sort_order, active)
            VALUES (%s, %s, %s, %s, TRUE)
            ON CONFLICT (key) DO UPDATE SET
                name = EXCLUDED.name,
                description = EXCLUDED.description,
                sort_order = EXCLUDED.sort_order,
                active = TRUE
        ''', (key, data["name"], data.get("description", ""), order))

    if keys:
        cur.execute("UPDATE groups SET active=FALSE WHERE key <> ALL(%s)", (keys,))
    else:
        cur.execute("UPDATE groups SET active=FALSE")

    active_triplets = set()
    for key in keys:
        for bel, ru in WORD_GROUPS[key]["words"]:
            active_triplets.add((key, bel, ru))
            cur.execute('''
                INSERT INTO words (group_key, word_bel, word_ru, active)
                VALUES (%s, %s, %s, TRUE)
                ON CONFLICT (group_key, word_bel, word_ru) DO UPDATE SET active=TRUE
            ''', (key, bel, ru))

    if keys:
        cur.execute(
            "SELECT id, group_key, word_bel, word_ru FROM words WHERE group_key = ANY(%s) AND active=TRUE",
            (keys,),
        )
        stale_ids = [r[0] for r in cur.fetchall() if (r[1], r[2], r[3]) not in active_triplets]
        if stale_ids:
            cur.execute("UPDATE words SET active=FALSE WHERE id = ANY(%s)", (stale_ids,))


