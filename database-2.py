def _fetch_distractors(cur, group_key, correct_word_id, correct_ru, n=3):
    """Подбирает n правдоподобных неправильных вариантов (уникальных по тексту
    перевода) сначала из той же темы, а если слов в теме не хватает — добирает
    из всего активного словаря, чтобы игра не падала на маленьких темах."""
    cur.execute('''
        SELECT id, word_bel, word_ru FROM words
        WHERE group_key=%s AND active=TRUE AND id <> %s AND word_ru <> %s
        ORDER BY random() LIMIT %s
    ''', (group_key, correct_word_id, correct_ru, max(n * 4, 12)))
    seen_ru = {correct_ru}
    result = []
    for wid, bel, ru in cur.fetchall():
        if ru in seen_ru:
            continue
        seen_ru.add(ru)
        result.append((wid, bel, ru))
        if len(result) >= n:
            return result

    if len(result) < n:
        need = n - len(result)
        exclude_ids = [correct_word_id] + [r[0] for r in result]
        cur.execute('''
            SELECT id, word_bel, word_ru FROM words
            WHERE active=TRUE AND NOT (id = ANY(%s)) AND word_ru <> %s
            ORDER BY random() LIMIT %s
        ''', (exclude_ids, correct_ru, max(need * 4, 12)))
        for wid, bel, ru in cur.fetchall():
            if ru in seen_ru:
                continue
            seen_ru.add(ru)
            result.append((wid, bel, ru))
            if len(result) >= n:
                break
    return result


